def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, required=True,
                        help="Destination containing tabs/ and figs/ (use local scratch first)")
    parser.add_argument("--font-dir", type=Path, help="Optional existing directory of TTF fonts")
    parser.add_argument("--scope", choices=("main", "appendix", "all"), default="all",
                        help="Select resources to render; appendix leaves main figures unchanged")
    args = parser.parse_args()
    apply_figure_style(register_font(args.font_dir))
    for name in ["tabs", "figs"]:
        (args.output_dir / name).mkdir(parents=True, exist_ok=True)
    if args.scope in ("main", "all"):
        generate_tables(args.output_dir / "tabs")
        generate_figures(args.output_dir / "figs")
    if args.scope in ("appendix", "all"):
        generate_appendix_tables(args.output_dir / "tabs")
        generate_appendix_figures(args.output_dir / "figs")
