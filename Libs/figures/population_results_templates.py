def apply_figure_style(font: str) -> None:
    """Apply figure-style's typography/frame rules without a skill-path dependency."""
    plt.rcParams.update({
        "font.family": "serif", "font.serif": [font], "font.size": 9,
        "axes.labelsize": 8, "axes.titlesize": 9, "axes.titlelocation": "left",
        "axes.linewidth": 0.6, "axes.spines.top": False,
        "axes.spines.right": False, "axes.grid": False,
        "xtick.labelsize": 8, "ytick.labelsize": 8,
        "xtick.direction": "out", "ytick.direction": "out",
        "xtick.major.size": 3, "ytick.major.size": 3,
        "xtick.major.width": 0.6, "ytick.major.width": 0.6,
        "legend.fontsize": 8, "legend.frameon": False,
        "lines.linewidth": 1.2, "patch.linewidth": 0.6,
        "pdf.fonttype": 42, "ps.fonttype": 42, "svg.fonttype": "none",
        "savefig.dpi": 300, "savefig.bbox": None,
        "figure.facecolor": "white", "axes.facecolor": "white",
    })


def register_font(directory: Path | None) -> str:
    if directory is None:
        return "DejaVu Serif"
    paths = sorted(directory.glob("*.ttf"))
    if not paths:
        raise FileNotFoundError(f"No TTF font files in {directory}")
    for path in paths:
        fm.fontManager.addfont(str(path))
    return fm.FontProperties(fname=str(paths[0])).get_name()


def row(label: str, values: list[str]) -> str:
    return " & ".join([label, *values]) + r" \\"


def table(path: Path, *, caption: str, label: str, columns: str,
          lines: list[str], wide: bool = False) -> None:
    environment = "table*" if wide else "table"
    width = r"\textwidth" if wide else r"\columnwidth"
    placement = "t" if wide else "!tb"
    row_spacing = "1" if wide else "1.08"
    text = [
        "% Generated by Libs/figures/population_results_templates.py; draft only.",
        rf"\begin{{{environment}}}[{placement}]", rf"\caption{{{caption}}}",
        rf"\label{{{label}}}", r"\centering", r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        rf"\renewcommand{{\arraystretch}}{{{row_spacing}}}",
        rf"\begin{{tabular*}}{{{width}}}{{@{{\extracolsep{{\fill}}}}{columns}@{{}}}}",
        r"\toprule", *lines, r"\bottomrule", r"\end{tabular*}",
        rf"\end{{{environment}}}", "",
    ]
    path.write_text("\n".join(text), encoding="utf-8")


