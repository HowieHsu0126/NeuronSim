def placeholder(ax: plt.Axes, title: str, xlabel: str, ylabel: str) -> None:
    ax.set_title(title, pad=5)
    # Coordinates are layout-only; suppress numeric ticks rather than invent scales.
    ax.set(xlim=(0, 1), ylim=(0, 1), xticks=[], yticks=[], xlabel=xlabel, ylabel=ylabel)
    ax.text(0.5, 0.5, "TBD", transform=ax.transAxes, ha="center", va="center",
            fontsize=11, color="#757575")


def save_figure(fig: plt.Figure, directory: Path, name: str) -> None:
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    bounds = fig.bbox
    for artist in fig.findobj(Text):
        if not artist.get_visible() or not artist.get_text():
            continue
        box = artist.get_window_extent(renderer)
        if box.x0 < -1 or box.y0 < -1 or box.x1 > bounds.x1 + 1 or box.y1 > bounds.y1 + 1:
            raise ValueError(f"Clipped text in {name}: {artist.get_text()!r}")
    for extension in ["pdf", "svg", "png"]:
        fig.savefig(directory / f"{name}.{extension}")
    plt.close(fig)


def figure_include(directory: Path, name: str, caption: str, *, description: str,
                   wide: bool = False) -> None:
    environment = "figure*" if wide else "figure"
    width = r"\textwidth" if wide else r"\columnwidth"
    placement = "t" if wide else "!tb"
    (directory / f"{name}.tex").write_text("\n".join([
        "% Generated by Libs/figures/population_results_templates.py; draft only.",
        rf"\begin{{{environment}}}[{placement}]", r"\centering",
        rf"\includegraphics[width={width}]{{{name}.pdf}}",
        rf"\caption{{{caption}}}", rf"\label{{fig:{name}}}",
        rf"\Description{{{description}}}",
        rf"\end{{{environment}}}", "",
    ]), encoding="utf-8")


